#!/usr/bin/env python3
"""
Builds the "open from disk" copy of the site's scripts and fonts.

Browsers refuse ES modules and web fonts on pages opened straight from a folder (file://),
so double-clicking index.html would show a plain page with no intro. For that case only,
each page loads two generated files instead:

  js/offline.js          every module in js/ combined into one classic script
  css/fonts-offline.css  the four fonts embedded as data URIs

The live site (http/https) never loads them. After changing anything in js/ or the fonts,
run from the project folder:

  python3 tools/build-offline.py

No dependencies beyond Python 3.
"""

import base64
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
JS = ROOT / "js"
ENTRY = "main.js"

STATIC_IMPORT = re.compile(r"^[ \t]*import[ \t]+(?P<what>[^'\"\n]+?)[ \t]+from[ \t]+['\"](?P<src>[^'\"]+)['\"];?[ \t]*$", re.M)
BARE_IMPORT = re.compile(r"^[ \t]*import[ \t]+['\"](?P<src>[^'\"]+)['\"];?[ \t]*$", re.M)
DYNAMIC_IMPORT = re.compile(r"\bimport\(\s*['\"](?P<src>[^'\"]+)['\"]\s*\)")
EXPORT_DECL = re.compile(r"^export[ \t]+(?P<kw>(?:async[ \t]+)?function\*?|class|const|let|var)[ \t]+(?P<name>[A-Za-z_$][\w$]*)", re.M)
EXPORT_DEFAULT = re.compile(r"^export[ \t]+default[ \t]+", re.M)


def resolve(from_id: str, spec: str) -> str:
    if not spec.startswith("."):
        sys.exit(f"{from_id}: only relative imports are supported ({spec})")
    path = (JS / from_id).parent.joinpath(spec).resolve()
    return path.relative_to(JS).as_posix()


def import_names(what: str, where: str) -> str:
    what = what.strip()
    if what.startswith("{") and what.endswith("}"):
        parts = []
        for item in what[1:-1].split(","):
            item = item.strip()
            if not item:
                continue
            m = re.fullmatch(r"([A-Za-z_$][\w$]*)(?:\s+as\s+([A-Za-z_$][\w$]*))?", item)
            if not m:
                sys.exit(f"{where}: cannot convert import {{ {item} }}")
            parts.append(f"{m.group(1)}: {m.group(2)}" if m.group(2) else m.group(1))
        return "{ " + ", ".join(parts) + " }"
    if re.fullmatch(r"[A-Za-z_$][\w$]*", what):
        return what  # default import, handled by the caller
    sys.exit(f"{where}: unsupported import form: import {what} from …")


def transform(mod_id: str, source: str, queue: list) -> str:
    def static(m):
        target = resolve(mod_id, m.group("src"))
        queue.append(target)
        names = import_names(m.group("what"), mod_id)
        if names.startswith("{"):
            return f"const {names} = __require({json.dumps(target)});"
        return f"const {names} = __require({json.dumps(target)}).default;"

    def bare(m):
        target = resolve(mod_id, m.group("src"))
        queue.append(target)
        return f"__require({json.dumps(target)});"

    def dynamic(m):
        target = resolve(mod_id, m.group("src"))
        queue.append(target)
        return f"__import({json.dumps(target)})"

    out = STATIC_IMPORT.sub(static, source)
    out = BARE_IMPORT.sub(bare, out)
    out = DYNAMIC_IMPORT.sub(dynamic, out)
    out = out.replace("import.meta.url", "__url")

    names = []

    def decl(m):
        names.append(m.group("name"))
        return f"{m.group('kw')} {m.group('name')}"

    out = EXPORT_DECL.sub(decl, out)
    out = EXPORT_DEFAULT.sub("__exports.default = ", out)
    leftover = re.search(r"^export\b.*$", out, re.M)
    if leftover:
        sys.exit(f"{mod_id}: unsupported export form: {leftover.group(0)}")
    if re.search(r"^[ \t]*import\b", out, re.M):
        sys.exit(f"{mod_id}: an import statement was not converted")

    # Module source is kept verbatim (no re-indenting), so template strings such as shaders are unchanged.
    tail = "".join(f"\n__exports.{n} = {n};" for n in names)
    return f"__defs[{json.dumps(mod_id)}] = function (__exports, __url) {{\n'use strict';\n{out.rstrip()}\n{tail}\n}};\n"


def build_js() -> str:
    queue, seen, chunks = [ENTRY], set(), []
    while queue:
        mod_id = queue.pop(0)
        if mod_id in seen:
            continue
        seen.add(mod_id)
        src = (JS / mod_id).read_text(encoding="utf-8")
        chunks.append(f"\n/* ── js/{mod_id} ── */\n" + transform(mod_id, src, queue))

    header = f"""/* INVITÉ Studio: offline copy of the site scripts, used only when a page is opened
   straight from a folder (file://), where browsers block ES modules.
   GENERATED by tools/build-offline.py from the modules in js/ ({len(seen)} files). Do not edit:
   change the modules, then run `python3 tools/build-offline.py`. The live site never loads this. */
(function () {{
  'use strict';
  var __root = new URL('..', (document.currentScript && document.currentScript.src) || location.href);
  var __defs = Object.create(null), __cache = Object.create(null);
  function __require(id) {{
    var m = __cache[id];
    if (m) return m.exports;
    if (!__defs[id]) throw new Error('offline copy: missing module ' + id);
    m = __cache[id] = {{ exports: {{}} }};
    __defs[id].call(undefined, m.exports, new URL('js/' + id, __root).href);
    return m.exports;
  }}
  function __import(id) {{ return new Promise(function (resolve) {{ resolve(__require(id)); }}); }}
"""
    footer = """
  /* Folder links ("work/jetour/") open a directory listing from disk, so point them at index.html. */
  function fixLinks() {
    document.querySelectorAll('a[href]').forEach(function (a) {
      var href = a.getAttribute('href');
      if (/^(?:[a-z][a-z0-9+.-]*:|#|\\/\\/)/i.test(href)) return;
      var m = href.match(/^([^?#]*)(.*)$/);
      if (m[1] === '' || /\\/$/.test(m[1])) a.setAttribute('href', m[1] + 'index.html' + m[2]);
    });
  }
  function boot() { fixLinks(); __require('main.js'); }
  if (document.readyState === 'loading') document.addEventListener('DOMContentLoaded', boot);
  else boot();
})();
"""
    return header + "".join(chunks) + footer


def build_fonts() -> str:
    css = (ROOT / "css" / "fonts.css").read_text(encoding="utf-8")
    fonts_dir = ROOT / "assets" / "fonts"

    def inline(m):
        name = m.group(1)
        data = base64.b64encode((fonts_dir / name).read_bytes()).decode("ascii")
        return f'url("data:font/woff2;base64,{data}")'

    # One data URI per face: drop the duplicate "woff2-variations" source line first.
    css = re.sub(r'src: url\("\.\./assets/fonts/([\w.-]+)"\) format\("woff2-variations"\),\s*\n\s*', "src: ", css)
    css = re.sub(r'url\("\.\./assets/fonts/([\w.-]+)"\)', inline, css)
    return ("/* GENERATED by tools/build-offline.py: the fonts from fonts.css, embedded so pages opened\n"
            "   straight from a folder (file://) can use them. The live site never loads this file. */\n" + css)


def main():
    js = build_js()
    (JS / "offline.js").write_text(js, encoding="utf-8")
    fonts = build_fonts()
    (ROOT / "css" / "fonts-offline.css").write_text(fonts, encoding="utf-8")
    print(f"js/offline.js          {len(js) / 1024:.0f} KB")
    print(f"css/fonts-offline.css  {len(fonts) / 1024:.0f} KB")


if __name__ == "__main__":
    main()
